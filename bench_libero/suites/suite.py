"""Suite loading — declarative task/case lists.

A suite is one YAML file: adding a task must not require touching code.

Case schema is copied from the existing `eval/val200_caseindex/cases.json`
(200 entries, produced by the current eval path), so an index generated by the
training repo can be consumed here unchanged:

    attempt_uid  case_index  episode_status  episode_uid
    outcome  selection_rank  shard  slot  split  worker_run_uid

`shard` + `slot` are what the env actually needs; the rest is provenance that
travels into the report so a result can be traced back to its source episode.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

REQUIRED_CASE_KEYS = ("shard", "slot")


@dataclass
class Case:
    """One evaluated episode."""

    shard: Path
    slot: int
    case_index: int = 0
    start_frame: int = 0
    max_frames: int | None = None
    # provenance, carried through to the report
    episode_uid: str | None = None
    attempt_uid: str | None = None
    worker_run_uid: str | None = None
    episode_status: str | None = None
    outcome: str | None = None
    selection_rank: int | None = None
    split: str | None = None

    @classmethod
    def from_dict(cls, payload: dict[str, Any], index: int = 0) -> Case:
        missing = [k for k in REQUIRED_CASE_KEYS if k not in payload]
        if missing:
            raise ValueError(f"case {index} missing required keys: {missing}")
        known = set(cls.__dataclass_fields__)
        kwargs = {k: v for k, v in payload.items() if k in known}
        kwargs["shard"] = Path(str(kwargs["shard"]))
        kwargs["slot"] = int(kwargs["slot"])
        kwargs.setdefault("case_index", index)
        return cls(**kwargs)

    def to_dict(self) -> dict[str, Any]:
        from dataclasses import asdict

        payload = asdict(self)
        payload["shard"] = str(self.shard)
        return payload


@dataclass
class Suite:
    """A task definition plus the cases it runs on."""

    name: str
    task: str = "cube_lift_follow_v1"
    description: str = ""
    physics_profile: str = "tro_mp_dataprod_venvshare_20260808.yaml"
    """Default is the data-production profile (physics truth). See
    log/physics_difference.txt for why the v10 eval pairing is not it."""
    interprior_root: str = "/mnt/venv_share/H800/Interprior"
    """Env code must come from the same checkout as the profile yaml."""
    cases: list[Case] = field(default_factory=list)
    # env-side defaults, overridable per case
    start_frame: int = 0
    #: First SOURCE frame of the object-flow plan -- distinct from `start_frame`,
    #: which only chooses where the simulation begins. The plan is a separate
    #: array, so cropping it from a different offset shifts the whole task in
    #: time. exp04 trained on source frames [121, 768) and zjw's eval crops the
    #: plan to exactly that. Leaving this at 0 while the object first moves near
    #: frame 463 hands the policy a plan whose motion is 121 frames late: it
    #: waits, then chases, and diverges (measured: arm j7 off by 1.25 rad at
    #: frame 100, where the teacher has not moved at all).
    plan_source_start: int = 0
    max_frames: int = 2000
    post_plan_frames: int = 0
    goal_source: str = "derived_shard"
    """derived_shard | authored_npz — authored uses the goal_traj toolchain."""
    goal_traj: str | None = None
    limit: int | None = None
    extra: dict[str, Any] = field(default_factory=dict)

    def resolved_cases(self) -> list[Case]:
        """Apply suite defaults and the optional limit."""

        out: list[Case] = []
        for case in self.cases[: self.limit] if self.limit else self.cases:
            if case.max_frames is None:
                case.max_frames = self.max_frames
            if not case.start_frame:
                case.start_frame = self.start_frame
            out.append(case)
        return out


def load_suite(path: Path) -> Suite:
    """Read a suite YAML. `cases_from` pulls an existing cases.json index."""

    import yaml

    path = Path(path)
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}

    raw_cases = list(payload.pop("cases", []) or [])
    cases_from = payload.pop("cases_from", None)
    if cases_from:
        index_path = Path(cases_from)
        if not index_path.is_absolute():
            index_path = path.parent / index_path
        raw_cases.extend(json.loads(index_path.read_text(encoding="utf-8")))

    known = set(Suite.__dataclass_fields__)
    kwargs = {k: v for k, v in payload.items() if k in known}
    kwargs.setdefault("name", path.stem)
    kwargs["cases"] = [Case.from_dict(c, i) for i, c in enumerate(raw_cases)]
    return Suite(**kwargs)


def discover(suites_dir: Path) -> dict[str, Path]:
    """Map suite name -> yaml path, for `bench tasks`."""

    return {p.stem: p for p in sorted(Path(suites_dir).glob("*.yaml"))}
