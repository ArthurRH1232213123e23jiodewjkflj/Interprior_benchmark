#!/usr/bin/env python
"""Install each LIBERO object's own texture atlas into its env dir.

The atlases are LIBERO's own files, ~83 MB over 21 objects, so they are
gitignored rather than committed (this repo tracks source and frozen truth, not
blobs). This script rebuilds them from a LIBERO assets tree, so a fresh
checkout can restore what git does not carry.

Per env dir it writes:
  texture.png  -- byte-identical copy of the atlas the object's .mtl names
  visual.mtl   -- generated, binds that atlas as map_Kd

`build_object_urdf.py` then emits an .obj carrying `mtllib visual.mtl` plus the
UVs from mesh.npz, and Isaac's URDF importer takes the atlas into the USD.
Run this BEFORE build_object_urdf.py; `verify_object_urdf.py` fails if an .obj
references a visual.mtl that is not present, so a missing install cannot pass
silently as an untextured spawn.

wine_bottle is deliberately skipped: LIBERO gives it three materials
(Glass/Label/Wine) that are Kd constants with no map_Kd, so it has no atlas and
a textureless spawn is the faithful outcome.

Usage:
  python install_textures.py --libero-assets ~/libero/LIBERO/libero/libero/assets
"""
from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
import re
import shutil
from pathlib import Path

LIB = Path(__file__).resolve().parent.parent
ENVS = LIB / "envs"
# The three asset families LIBERO ships objects in; each names its files
# differently (textured.obj/texture_map.png, <name>.obj/texture.png, ...).
FAMILIES = ("stable_hope_objects", "stable_scanned_objects", "turbosquid_objects")

MTL_TEMPLATE = """# GENERATED by build_env/install_textures.py -- do not hand-edit.
# Binds the LIBERO atlas copied alongside as texture.png. The UVs come from
# mesh.npz and are LIBERO's own, written unchanged (no V flip).
newmtl libero_visual
Kd 1 1 1
map_Kd texture.png
"""


def find_source_dir(assets_root: Path, env_id: str) -> Path | None:
    for fam in FAMILIES:
        d = assets_root / fam / env_id
        if d.is_dir():
            return d
    return None


def atlas_for(src_dir: Path) -> Path | None:
    """The atlas this object's own .mtl names, not a guess from the filenames.

    Multi-part objects (moka_pot body/handle, wine_bottle glass/label/cork) have
    several .mtl files; the visual mesh with the most geometry is the one
    mesh.npz was built from, so its .mtl is the one that matters.
    """
    objs = [p for p in sorted(src_dir.glob("*.obj"))
            if not re.search(r"_(col|coll)\.obj$", p.name)]
    if not objs:
        return None
    main = max(objs, key=lambda p: p.stat().st_size)
    mtl = main.with_suffix(".mtl")
    if not mtl.exists():
        cands = sorted(src_dir.glob("*.mtl"))
        mtl = cands[0] if cands else None
    if mtl is None or not mtl.exists():
        return None
    for line in mtl.read_text(errors="ignore").splitlines():
        if line.strip().startswith("map_Kd"):
            cand = src_dir / line.split()[-1]
            return cand if cand.exists() else None
    return None  # no map_Kd: the object is colour-only in LIBERO


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--libero-assets", required=True,
                    help="LIBERO assets root, e.g. ~/libero/LIBERO/libero/libero/assets")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    root = Path(os.path.expanduser(args.libero_assets))
    if not root.is_dir():
        raise SystemExit(f"LIBERO assets root not found: {root}")

    env_ids = sorted(p.name for p in ENVS.iterdir()
                     if (p / "mesh.npz").exists())
    report, installed, colour_only, missing = {}, [], [], []
    for env_id in env_ids:
        d = ENVS / env_id
        src = find_source_dir(root, env_id)
        if src is None:
            missing.append(env_id)
            report[env_id] = {"status": "NO_SOURCE_DIR"}
            continue
        atlas = atlas_for(src)
        if atlas is None:
            colour_only.append(env_id)
            report[env_id] = {"status": "COLOUR_ONLY", "src": str(src)}
            # leave any stale files out of the way so the .obj falls back cleanly
            if not args.dry_run:
                for stale in ("texture.png", "visual.mtl"):
                    (d / stale).unlink(missing_ok=True)
            continue
        sha = hashlib.sha256(atlas.read_bytes()).hexdigest()
        if not args.dry_run:
            shutil.copy2(atlas, d / "texture.png")
            (d / "visual.mtl").write_text(MTL_TEMPLATE, encoding="utf-8")
        installed.append(env_id)
        report[env_id] = {"status": "OK", "atlas": str(atlas.relative_to(root)),
                          "sha256": sha, "bytes": atlas.stat().st_size}

    if not args.dry_run:
        (LIB / "texture_install_report.json").write_text(
            json.dumps(report, indent=1), encoding="utf-8")
    print(f"installed {len(installed)}  colour-only {len(colour_only)}  "
          f"no-source {len(missing)}  of {len(env_ids)} envs")
    for env_id in colour_only:
        print(f"  colour-only (no map_Kd in LIBERO): {env_id}")
    for env_id in missing:
        print(f"  NO SOURCE DIR: {env_id}")
    if missing:
        raise SystemExit("some envs had no LIBERO source dir -- wrong assets root?")
    print("\nnext: python build_env/build_object_urdf.py   (writes .obj with UV + mtllib)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
