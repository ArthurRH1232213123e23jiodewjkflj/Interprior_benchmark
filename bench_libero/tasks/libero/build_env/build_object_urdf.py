"""Generate a spawnable URDF per LIBERO env from its mesh.npz.

WHY URDF AND NOT THE USD WE ALREADY HAVE: the TRO-MP env spawns objects through
`assets.object_urdf` only -- `scene_utils.py:1929` takes `urdf_paths =
[Path(assets_cfg.object_urdf)]` and runs `_convert_urdf_to_usd()` itself
(`:1964`). The assets dataclass has no USD field at all (grepped
`simtoolreal_env_cfg.py`: `object_urdf: str = ""`, no `object_usd`). So
alphabet_soup.usd cannot be handed to this env directly, however good it is --
DexVerse's PickObject task takes a `UsdFileCfg` and is a different code path.

Each URDF gets:
  * an OBJ sidecar exported from mesh.npz, in the mesh's own coordinates (the
    origin convention `goal_traj` tracks -- see canonical_from_env_mesh)
  * <visual> and <collision> both referencing that OBJ
  * inertia from the mesh's own volume at a stated density, not a guess

Collision uses the full mesh; Isaac's URDF importer decomposes it. The convex
decomposition the soup USD carried is NOT reproduced here -- that is a real
difference from the DexVerse asset, recorded in each URDF's header.
"""
from __future__ import annotations

import json, os, sys
from pathlib import Path
import numpy as np

LIB = Path("/home/huangsicheng/benchmark/bench_libero/tasks/libero")
ENVS = LIB / "envs"
PROPS = LIB / "props"
DENSITY = 800.0  # kg/m^3, the same value the cube URDF uses


def mesh_volume_and_com(verts: np.ndarray, faces: np.ndarray):
    """Signed-tetrahedron volume + centre of mass. Returns (vol, com, inertia@density=1)."""
    a, b, c = verts[faces[:, 0]], verts[faces[:, 1]], verts[faces[:, 2]]
    # per-tet signed volume (origin as apex)
    vol6 = np.einsum("ij,ij->i", a, np.cross(b, c))
    vol = float(vol6.sum() / 6.0)
    if abs(vol) < 1e-12:
        return 0.0, np.zeros(3), np.zeros((3, 3))
    centroids = (a + b + c) / 4.0
    com = (centroids * vol6[:, None]).sum(axis=0) / vol6.sum()
    return vol, com, None


def write_obj(path: Path, verts: np.ndarray, faces: np.ndarray) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# exported from mesh.npz by build_env/build_object_urdf.py\n")
        fh.write("# mesh coordinates preserved (origin convention goal_traj tracks)\n")
        for v in verts:
            fh.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
        for f in faces:
            fh.write(f"f {f[0] + 1} {f[1] + 1} {f[2] + 1}\n")


def build(env_id: str, root: Path = ENVS) -> dict:
    d = root / env_id
    with np.load(d / "mesh.npz", allow_pickle=True) as p:
        verts = np.asarray(p["verts"], dtype=np.float64)
        faces = np.asarray(p["faces"], dtype=np.int64)

    extent = float(np.ptp(verts, axis=0).max())
    if not 0.01 <= extent <= 1.0:
        raise ValueError(f"{env_id}: extent {extent:.4f} m implausible -- check units")

    obj_rel = f"{env_id}.obj"
    write_obj(d / obj_rel, verts, faces)

    vol, com, _ = mesh_volume_and_com(verts, faces)
    watertight = vol > 0
    bbox_min, bbox_max = verts.min(axis=0), verts.max(axis=0)
    size = bbox_max - bbox_min

    if watertight:
        mass = DENSITY * vol
        mass_note = f"density {DENSITY} kg/m^3 x mesh volume {vol:.6e} m^3"
        centre = com
    else:
        # Non-watertight scan: fall back to the bbox at the same density, but say so.
        vol_bbox = float(np.prod(np.maximum(size, 1e-6)))
        mass = DENSITY * vol_bbox * 0.5
        mass_note = (f"mesh not watertight (signed volume {vol:.3e}); "
                     f"used 0.5 x bbox volume {vol_bbox:.6e} m^3 at {DENSITY} kg/m^3")
        centre = 0.5 * (bbox_min + bbox_max)

    mass = float(max(mass, 0.005))
    # Solid-box inertia about the COM at this mass -- an approximation, stated as one.
    ix = mass * (size[1] ** 2 + size[2] ** 2) / 12.0
    iy = mass * (size[0] ** 2 + size[2] ** 2) / 12.0
    iz = mass * (size[0] ** 2 + size[1] ** 2) / 12.0

    is_prop = (root == PROPS)
    role = ("static scene fixture (props/): furniture the tasks depend on, the\n"
            "     support surfaces goals end on. Spawned KINEMATIC, so the mass and\n"
            "     inertia below never act; they are computed the same way regardless\n"
            "     rather than faked, in case it is ever spawned dynamic.\n\n"
            "     ARTICULATION IS BAKED AWAY. Several of these have drawers, doors or\n"
            "     knobs in LIBERO and are one rigid mesh here (props_registry.json\n"
            "     flags `articulated_baked`). A task whose verb is `close the drawer`\n"
            "     cannot be scored on this asset."
            if is_prop else
            "graspable target object (envs/), one of the 22 LIBERO target assets.")
    urdf = f"""<?xml version="1.0"?>
<!-- GENERATED by tasks/libero/build_env/build_object_urdf.py. Do not hand edit.

     LIBERO object `{env_id}`, spawnable by the TRO-MP env.
     Role: {role}

     WHY a URDF when envs/{env_id}/ may also hold a USD: this env spawns objects
     only through `assets.object_urdf` (scene_utils.py:1929, which calls
     _convert_urdf_to_usd at :1964). The assets dataclass declares no USD field,
     so a ready-made USD cannot be handed to this code path.

     Mesh coordinates are PRESERVED, not re-centred: 11 of 22 LIBERO envs have
     their mesh origin at the object's base, and `goal_traj` tracks that origin.
     Re-centring would offset the object from its own trajectory every frame.

     Mass: {mass_note}
     Inertia: solid-box approximation about the COM at that mass, NOT the true
     mesh inertia tensor. Adequate for a graspable tabletop object; revisit if
     spin dynamics matter.

     Collision: the full mesh, decomposed by Isaac's URDF importer. The convex
     decomposition authored in the DexVerse USD is NOT reproduced here.
-->
<robot name="{env_id}">
  <link name="{env_id}">
    <inertial>
      <origin xyz="{centre[0]:.6f} {centre[1]:.6f} {centre[2]:.6f}" rpy="0 0 0"/>
      <mass value="{mass:.6f}"/>
      <inertia ixx="{ix:.6e}" ixy="0" ixz="0" iyy="{iy:.6e}" iyz="0" izz="{iz:.6e}"/>
    </inertial>
    <visual>
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry><mesh filename="{obj_rel}" scale="1 1 1"/></geometry>
    </visual>
    <collision>
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry><mesh filename="{obj_rel}" scale="1 1 1"/></geometry>
    </collision>
  </link>
</robot>
"""
    # XML forbids "--" inside a comment; a malformed header makes every URDF
    # unparseable while still looking fine on screen. Parse before writing.
    import xml.etree.ElementTree as _ET
    try:
        _ET.fromstring(urdf)
    except _ET.ParseError as ex:
        raise ValueError(f"{env_id}: generated URDF is not well-formed XML: {ex}") from ex

    (d / f"{env_id}.urdf").write_text(urdf, encoding="utf-8")
    return dict(env_id=env_id, urdf=f"{env_id}.urdf", obj=obj_rel,
                mass_kg=round(mass, 5), watertight=bool(watertight),
                volume_m3=float(vol), extent_m=round(extent, 4),
                bbox_min_m=[round(float(v), 5) for v in bbox_min],
                bbox_max_m=[round(float(v), 5) for v in bbox_max],
                size_m=[round(float(v), 5) for v in size],
                inertial_origin=[round(float(v), 5) for v in centre],
                n_verts=int(len(verts)), n_faces=int(len(faces)))


def main():
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--props", action="store_true",
                    help="build props/ (the 11 static scene fixtures) instead of envs/")
    ap.add_argument("--only", default=None, help="one category only")
    a = ap.parse_args()
    root = PROPS if a.props else ENVS
    names = [a.only] if a.only else sorted(os.listdir(root))

    out = []
    for e in names:
        if not (root / e).is_dir():
            continue
        try:
            out.append(build(e, root))
        except Exception as ex:
            print(f"  {e}: FAILED {ex}")
    print(f"{'env':22s} {'mass_kg':>8s} {'watertight':>10s} {'extent':>7s} {'verts':>7s}")
    for r in out:
        print(f"{r['env_id']:22s} {r['mass_kg']:8.4f} {str(r['watertight']):>10s} "
              f"{r['extent_m']:7.4f} {r['n_verts']:7d}")
    index = "props_urdf_index.json" if a.props else "object_urdf_index.json"
    (LIB / index).write_text(
        json.dumps({"density_kg_m3": DENSITY, "root": root.name,
                    "kinematic_when_spawned": bool(a.props),
                    "objects": out}, indent=1) + "\n")
    print(f"\nwrote {len(out)} URDF+OBJ pairs into {root.name}/, index at {index}")
    nw = [r["env_id"] for r in out if not r["watertight"]]
    if nw:
        print(f"NOT watertight ({len(nw)}): {nw}")


if __name__ == "__main__":
    main()
